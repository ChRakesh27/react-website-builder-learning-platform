drop trigger if exists workspace_search_document_project on public.projects;
create trigger workspace_search_document_project
before insert or update on public.projects
for each row execute function public.workspace_search_document_project();

drop trigger if exists workspace_search_document_employee on public.employees;
create trigger workspace_search_document_employee
