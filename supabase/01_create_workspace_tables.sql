create extension if not exists pg_trgm;

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  key text not null unique,
  owner text,
  status text default 'Planning',
  description text,
  start_date date,
  deadline date,
  due date,
  progress integer default 0,
  members integer default 0,
  database_name text,
  database_plan text,
  account_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  search_document tsvector
);

create table if not exists public.employees (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  role text,
  email text,
  phone text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  search_document tsvector
);

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  project_id bigint references public.projects(id) on delete cascade,
  title text not null,
  type text default 'Task',
  priority text default 'Medium',
  status text default 'To Do',
  assignee text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  search_document tsvector
);

create table if not exists public.subtasks (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  task_id bigint references public.tasks(id) on delete cascade,
  title text not null,
  status text,
  priority text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  search_document tsvector
);

create or replace function public.workspace_search_document_project()
returns trigger
language plpgsql
as $$
begin
  new.search_document :=
    setweight(to_tsvector('english', coalesce(new.name, '')), 'A') ||
    setweight(to_tsvector('english', coalesce(new.key, '')), 'A') ||
    setweight(to_tsvector('english', coalesce(new.owner, '')), 'B') ||
    setweight(to_tsvector('english', coalesce(new.status, '')), 'B') ||
    setweight(to_tsvector('english', coalesce(new.description, '')), 'C') ||
    setweight(to_tsvector('english', coalesce(new.due::text, '')), 'D') ||
    setweight(to_tsvector('english', coalesce(new.start_date::text, '')), 'D') ||
    setweight(to_tsvector('english', coalesce(new.deadline::text, '')), 'D');
  return new;
end;
$$;

